/* 把一个 region 字符串解析成国家/地区数组（去重、保持出现顺序） */
function of(region){
  if(!region) return [];
  var out=[], seen={};
  function push(v){ if(v && !seen[v]){ seen[v]=1; out.push(v); } }

  // 先按迁徙箭头、间隔点、并列词、括号切成原子片段
  var parts=String(region)
    .split(/[→>]/)
    .join('·')
    .split('·')
    .join('|')
    .replace(/[与、,，]/g,'|')
    .replace(/[（(]/g,'|')
    .replace(/[）)]/g,'|')
    .split('|');

  parts.forEach(function(raw){
    var s=(raw||'').trim();
    if(!s) return;
    // 1) 本身就是国家名
    if(COUNTRY_SET[s]){ push(s); return; }
    // 2) 城市/朝代精确映射
    if(CITY[s]){ push(CITY[s]); return; }
    // 3) 形如「美国纽约」「法国巴黎」的黏连写法：先看是否以某个国家名开头
    var hitCountry=null;
    for(var i=0;i<COUNTRY.length;i++){
      if(s.indexOf(COUNTRY[i])===0){ hitCountry=COUNTRY[i]; break; }
    }
    if(hitCountry){ push(hitCountry); return; }
    // 4) 片段里包含某个已知城市名（如「帕哈里 古勒」「中部沙漠 安马杰拉族」）
    var keys=Object.keys(CITY), matched=false;
    for(var j=0;j<keys.length;j++){
      if(s.indexOf(keys[j])>=0){ push(CITY[keys[j]]); matched=true; break; }
    }
    if(matched) return;
    // 5) 片段里包含某个国家名（如「德意志汉诺威」已被 3 覆盖，这里兜底）
    for(var k=0;k<COUNTRY.length;k++){
      if(s.indexOf(COUNTRY[k])>=0){ push(COUNTRY[k]); return; }
    }
    // 6) 完全无法识别的（多为族群名/修饰语）忽略，不产生垃圾标签
  });

  return out;
}

